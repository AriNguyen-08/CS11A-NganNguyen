animals = ['Dog', 'Cat', 'Lion', 'Tiger', 'Elephant', 'Giraffe', 'Monkey']   #Create a list of seven animals
for animal in animals:          #Use a loop to go through each animal in the list
    print(animal)               #Print each animal's name
print("The first three animals in the list are:", animals[:3])  #Print the first three animals in the list
print("Three animals in the middle of the list are:", animals[2:5])   #Print three animals in the middle of the list
print("The last three animals in the list are:", animals[-3:])    #Print the last three animals in the list
